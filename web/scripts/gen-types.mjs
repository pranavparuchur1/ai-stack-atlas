// Generate TypeScript types from the pipeline's JSON Schema (single source of truth:
// pipeline/models.py -> `uv run pipeline export-schema` -> schema/*.json -> here).
// One module per schema so same-named helper aliases from different schemas never collide.
import { compileFromFile } from "json-schema-to-typescript";
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const schemaDir = fileURLToPath(new URL("../../schema/", import.meta.url));
const outDir = fileURLToPath(new URL("../src/types/generated/", import.meta.url));
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });
const banner = "/* eslint-disable */\n// AUTO-GENERATED by scripts/gen-types.mjs from schema/*.schema.json - do not edit.\n";
const files = readdirSync(schemaDir).filter((f) => f.endsWith(".schema.json")).sort();
for (const f of files) {
  const ts = await compileFromFile(schemaDir + f, { bannerComment: banner, additionalProperties: false, cwd: schemaDir });
  writeFileSync(outDir + f.replace(".schema.json", ".ts"), ts);
}
console.log(`generated ${files.length} modules -> src/types/generated/`);
